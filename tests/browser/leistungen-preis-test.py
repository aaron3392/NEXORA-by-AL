import sys; sys.path.insert(0,'/home/claude/NEXORA-by-AL/tests/browser')
from admin_helper import *
R=[]
def ok(n,c): R.append(bool(c)); print(('OK   ' if c else 'FEHLER '),n)
with sync_playwright() as p:
    br=p.chromium.launch(); c=br.new_context(viewport={"width":1440,"height":900}); pg=c.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    login(pg)
    ok('Admin-Logo fuehrt zum Dashboard', (pg.click('.logo'), pg.wait_for_timeout(300), pg.inner_text('h1'))[2]=='Dashboard')
    pg.click("[data-v='webseiteneinstellungen']"); pg.wait_for_timeout(400)
    ok('Mindestpreis-Gruppe mit 11 Leistungen', pg.locator('[data-svc]').count()==11)
    pg.locator('[data-svc]').nth(0).fill('990'); pg.locator('[data-svc]').nth(3).fill('ab 1.500 € netto')
    pg.click('#save-website-settings'); pg.wait_for_timeout(300)
    ok('Gespeichert (2 Preise)', pg.evaluate("Object.keys(NX.db.settings.servicePrices).length")==2)
    pg2=c.new_page(); pg2.goto('http://localhost:8765/leistungen.html'); pg2.wait_for_selector('.nx-service'); pg2.wait_for_timeout(300)
    t=pg2.inner_text('#svc')
    ok('Zahl wird zu "ab 990 €"','ab 990 €' in t)
    ok('Freitext wird unveraendert angezeigt','ab 1.500 € netto' in t)
    ok('Nur 2 Preise sichtbar', pg2.locator('.nx-from').count()==2)
    pg2.screenshot(path='/home/claude/NEXORA-by-AL/screenshots/27-leistungen-mindestpreis.png')
    pg.click('.logo'); pg.click("[data-v='webseiteneinstellungen']"); pg.wait_for_timeout(300)
    pg.locator('[data-svc]').nth(0).fill(''); pg.click('#save-website-settings'); pg2.reload(); pg2.wait_for_selector('.nx-service')
    ok('Preis entfernen blendet ihn aus', pg2.locator('.nx-from').count()==1)
    ok('Keine JS-Fehler', not errs)
print(f'LEISTUNGEN-PREIS: {sum(R)}/{len(R)} bestanden'); sys.exit(0 if all(R) else 1)
