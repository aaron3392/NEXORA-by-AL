"""Browser-Test für die neuen Zusatzfunktionen (Startseite + Admin). Voraussetzung: http://localhost:8765/ läuft."""
from playwright.sync_api import sync_playwright
B = "http://localhost:8765/"
res = []
def ok(n, c): res.append(bool(c)); print(("PASS " if c else "FAIL ") + n)
with sync_playwright() as p:
    br = p.chromium.launch()
    # --- Startseite ---
    pg = br.new_page(viewport={"width": 390, "height": 844}); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(B + "index.html"); pg.wait_for_timeout(700)
    ok("Vertrauensleiste vorhanden (4 Punkte)", pg.locator(".nx-trust li").count() == 4)
    ok("FAQ vorhanden (5 Fragen)", pg.locator(".nx-faq details").count() == 5)
    ok("Handy-Button anfangs verborgen", "on" not in (pg.get_attribute(".nx-sticky", "class") or "").split())
    pg.evaluate("scrollTo(0, 1400)"); pg.wait_for_timeout(500)
    ok("Handy-Button erscheint nach dem Hero", "on" in pg.get_attribute(".nx-sticky", "class").split())
    H = pg.evaluate("document.body.scrollHeight")
    for y in range(0, H, 400): pg.evaluate(f"scrollTo(0,{y})"); pg.wait_for_timeout(100)
    pg.wait_for_timeout(500)
    ok("Alle Abschnitte werden nach Scrollen sichtbar", pg.evaluate("document.querySelectorAll('.nx-rv:not(.nx-in)').length") == 0)
    ok("Kein Quer-Scroll", not pg.evaluate("document.documentElement.scrollWidth>innerWidth"))
    pg.locator(".nx-faq summary").first.click(); ok("FAQ klappt auf", pg.evaluate("document.querySelector('.nx-faq details').open"))
    ok("Button führt zur Anfrage", pg.get_attribute(".nx-sticky a", "href") == "anfrage.html")
    ok("Keine JS-Fehler Startseite", not errs)
    # reduzierte Bewegung: nichts bleibt versteckt
    ctx = br.new_context(viewport={"width": 1440, "height": 900}, reduced_motion="reduce"); q = ctx.new_page()
    q.goto(B + "index.html"); q.wait_for_timeout(600)
    ok("Reduzierte Bewegung: keine versteckten Elemente", q.evaluate("document.querySelectorAll('.nx-rv').length") == 0)
    # --- Admin ---
    a = br.new_page(viewport={"width": 1440, "height": 900}); aerr = []
    a.on("pageerror", lambda e: aerr.append(str(e)))
    a.goto(B + "admin/index.html"); a.wait_for_timeout(500)
    a.fill("input[type=text],input:not([type])", "admin2026"); a.fill("input[type=password]", "N123456789")
    a.click("form button[type=submit], form .btn"); a.wait_for_timeout(1000)
    ok("Dashboard: Handlungsbedarf", a.locator(".nx-ax-todo li").count() >= 1)
    ok("Dashboard: kein Button „Jetzt sichern“ mehr", a.locator(".nx-ax-bk").count() == 0 and a.locator("[data-ax-backup]").count() == 0)
    for lbl, hsh in [("+ Neue Rechnung", "verrechnung-rechnungen"), ("+ Neues Angebot", "verrechnung-angebote"), ("+ Neues Projekt", "projekte"), ("+ Zeit erfassen", "zeit-eintraege")]:
        a.evaluate("document.querySelectorAll('.ov').forEach(e=>e.remove());location.hash='dashboard'"); a.wait_for_timeout(600)
        a.click(f'.nx-ax-quick button:has-text("{lbl}")'); a.wait_for_timeout(800)
        ok(f"Schnellaktion {lbl} öffnet Formular", a.evaluate("location.hash") == "#" + hsh and a.locator(".ov [role=dialog]").count() == 1)
    a.evaluate("document.querySelectorAll('.ov').forEach(e=>e.remove());location.hash='verrechnung-rechnungen'"); a.wait_for_timeout(800)
    alle = a.locator("#tb tbody tr").count(); a.click('.nx-ax-chip[data-v="Überfällig"]'); a.wait_for_timeout(300)
    ok("Status-Chip filtert Liste", 0 < a.locator("#tb tbody tr").count() < alle and a.input_value("#f") == "Überfällig")
    a.click('.nx-ax-chip[data-v=""]'); a.wait_for_timeout(300)
    ok("Chip „Alle“ setzt Filter zurück", a.locator("#tb tbody tr").count() == alle)
    a.evaluate("location.hash='dashboard'"); a.wait_for_timeout(600)
    # --- weitere Ergänzungen ---
    l = br.new_page(viewport={"width": 1440, "height": 900}); lerr = []
    l.on("pageerror", lambda e: lerr.append(str(e)))
    l.goto(B + "leistungen.html"); l.wait_for_timeout(800)
    alle = l.locator("#svc .nx-card:visible").count()
    l.click('.nx-filter .nx-chip:has-text("Betreuung")'); l.wait_for_timeout(200)
    ok("Leistungsfilter: Betreuung zeigt 2 von 11", alle == 11 and l.locator("#svc .nx-card:visible").count() == 2)
    l.click(".nx-filter .nx-chip >> nth=0"); l.wait_for_timeout(200)
    ok("Leistungsfilter: Alle zeigt wieder 11", l.locator("#svc .nx-card:visible").count() == 11)
    l.goto(B + "index.html"); l.wait_for_timeout(600)
    l.evaluate("document.getElementById('steps').scrollIntoView({block:'center'})"); l.wait_for_timeout(800)
    ok("Zeitleiste füllt sich beim Scrollen", float(l.evaluate("document.getElementById('steps').style.getPropertyValue('--p')") or 0) > 0.3)
    ok("Nach-oben-Button erscheint", "on" in l.get_attribute(".nx-ax-top", "class").split())
    ok("Keine JS-Fehler Leistungen/Start", not lerr)
    a.evaluate("document.querySelectorAll('.ov').forEach(e=>e.remove());location.hash='dashboard'"); a.wait_for_timeout(500)
    a.keyboard.press("/"); a.keyboard.type("mia"); a.wait_for_timeout(300)
    ok("Taste / fokussiert die Suche und findet Treffer", a.locator(".nx-ax-res button").count() >= 3)
    a.click(".nx-ax-res button >> nth=0"); a.wait_for_timeout(700)
    ok("Suchtreffer öffnet gefilterte Liste", a.evaluate("location.hash") == "#anfragen" and a.input_value("#q") != "")
    a.evaluate("location.hash='projekte'"); a.wait_for_timeout(500); a.keyboard.press("n"); a.wait_for_timeout(400)
    ok("Taste N öffnet „Neu“-Formular", a.locator(".ov [role=dialog]").count() == 1)
    ok("Keine JS-Fehler Admin", not aerr)
print(f"Ergebnis: {sum(res)}/{len(res)} bestanden.")
raise SystemExit(0 if all(res) else 1)
