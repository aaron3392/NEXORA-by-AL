import sys; sys.path.insert(0,'/home/claude/NEXORA-by-AL/tests/browser')
from admin_helper import *
R=[]
def ok(n,c): R.append(bool(c)); print(('OK   ' if c else 'FEHLER '),n)
with sync_playwright() as p:
    br=p.chromium.launch(); pg=br.new_page(viewport={"width":1440,"height":900}); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    login(pg)
    pg.evaluate("""()=>{const D=NX.db;[['2026-10-05'],['2026-10-06'],['2026-10-14'],['2026-11-03'],['2025-12-20']].forEach((a,i)=>D.time.push({id:'ZT'+i,date:a[0],start:'09:00',end:'11:00',brk:0,billable:true,customerId:'',projectId:'',desc:'t'}))}""")
    pg.click(r".side >> text=/^\s*Zeiterfassung\s*$/ >> nth=0"); pg.wait_for_timeout(300)
    pg.click("[data-v='zeit-uebersicht']"); pg.wait_for_timeout(500)
    rows=lambda: pg.locator('#ov tbody tr').count()
    n0=rows(); ok('Ohne Filter: alle Tage sichtbar (>=5)',n0>=5)
    pg.fill('#f-df','2026-10-05'); pg.wait_for_timeout(200)
    ok('Bis-Datum wird automatisch auf Von-Datum gesetzt',pg.input_value('#f-dt')=='2026-10-05')
    ok('Nur ein Tag',rows()==1)
    pg.fill('#f-dt','2026-10-14'); pg.wait_for_timeout(200)
    ok('Von/Bis-Bereich = 3 Tage',rows()==3)
    pg.select_option('#md','week'); pg.wait_for_timeout(200)
    pg.fill('#f-wk','2026-W41'); pg.wait_for_timeout(200)
    ok('Kalenderwoche 41 = 1 Zeile mit 2 Eintraegen',rows()==1 and '2026-KW41' in pg.inner_text('#ov'))
    pg.select_option('#md','month'); pg.wait_for_timeout(200)
    pg.fill('#f-mf','2026-11'); pg.wait_for_timeout(200)
    ok('Monat von ohne bis = nur November',rows()==1 and '2026-11' in pg.inner_text('#ov'))
    pg.fill('#f-mt','2026-11'); pg.fill('#f-mf','2026-10'); pg.wait_for_timeout(200)
    ok('Monat Oktober bis November = 2 Zeilen',rows()==2)
    pg.fill('#f-mf','2030-01'); pg.fill('#f-mt','2030-02'); pg.wait_for_timeout(200)
    ok('Leerer Bereich zeigt Hinweis','Keine Einträge im gewählten Zeitraum' in pg.inner_text('#ov'))
    pg.click('#f-reset'); pg.wait_for_timeout(200); ok('Zuruecksetzen zeigt wieder alles',rows()>=3)
    pg.select_option('#md','day'); pg.wait_for_timeout(200); pg.screenshot(path='/home/claude/NEXORA-by-AL/screenshots/26-zeit-uebersicht-filter.png')
    ok('Keine JS-Fehler',not errs)
print(f'ZEIT-FILTER: {sum(R)}/{len(R)} bestanden'); sys.exit(0 if all(R) else 1)
